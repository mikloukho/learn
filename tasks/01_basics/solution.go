// Sum — эталонно, править нечего.
func Sum(a, b int) int {
	return a + b
}

// Divide.
//
// БЫЛО:
//
//	if b == 0 {
//	    return 0, fmt.Errorf("divide by zero")
//	}
//
// Работает, но fmt.Errorf без единого глагола форматирования — это errors.New
// с лишним разбором строки в рантайме. Правило: нет %-подстановки — errors.New.
// go vet и линтеры на это ругаются.
//
// Второе: текст ошибки пишется с маленькой буквы и БЕЗ точки — ошибки
// оборачивают друг в друга, и текст склеивается в одну строку. У тебя так и есть.
func Divide(a, b float64) (float64, error) {
	if b == 0 {
		return 0, errors.New("divide by zero")
	}

	return a / b, nil
}

// Fizzbuzz — у тебя был TODO.
//
// Ключевое: сначала проверяем 15, потом 3 и 5. Если начать с 3, то 15
// никогда не дойдёт до нужной ветки. Вариант ниже — через накопление строки,
// он не требует проверки на 15 вообще и лучше расширяется (добавь делитель 7 —
// комбинаций станет не 4, а 8, и в лоб их писать замучаешься).
func Fizzbuzz(n int) string {
	var b strings.Builder

	if n%3 == 0 {
		b.WriteString("Fizz")
	}
	if n%5 == 0 {
		b.WriteString("Buzz")
	}
	if b.Len() == 0 {
		return fmt.Sprint(n)
	}

	return b.String()
}

// MinMax.
//
// БЫЛО:
//
//	if len(nums) < 1 { ... }
//	minLocal := nums[0]
//	maxLocal := nums[0]
//	for i := 1; i < len(nums); i++ {
//	    if nums[i] < minLocal { minLocal = nums[i] }
//	    if nums[i] > maxLocal { maxLocal = nums[i] }
//	}
//	return minLocal, maxLocal, nil
//
// Логика правильная. Три замечания по стилю:
//
//  1. len(nums) < 1 → len(nums) == 0. Длина не бывает отрицательной,
//     и читатель не должен об этом задумываться.
//
//  2. minLocal/maxLocal не нужны: min и max УЖЕ объявлены в сигнатуре как
//     именованные возвращаемые значения. Ты завёл вторую пару переменных
//     рядом с первой — это и есть та неоптимальность, которую ты чуял.
//
//  3. Индексный цикл `for i := 1; i < len(nums); i++` — привычка из PHP.
//     В Go идиома это range. Здесь нужен range со сдвигом: nums[1:].
//     Срез не копирует массив, он бесплатный.
//
// ВНИМАНИЕ: с Go 1.21 min и max — ВСТРОЕННЫЕ функции. Назвав так именованные
// возвращаемые значения, ты затеняешь их внутри всей функции: встроенный
// max(a, b) здесь уже не вызвать. Компилятор промолчит, а код сломается
// неочевидно. В реальном коде такие имена лучше не брать.
// В go.mod у тебя стоит 1.20, поэтому пока их вообще нет.
func MinMax(nums ...int) (min, max int, err error) {
	if len(nums) == 0 {
		return 0, 0, errors.New("empty input")
	}

	min, max = nums[0], nums[0]

	for _, n := range nums[1:] {
		if n < min {
			min = n
		}
		if n > max {
			max = n
		}
	}

	return min, max, nil
}

// DeferDemo.
//
// Твой код верный, разбираю ВЫВОД — он неочевидный.
//
// Реальный вывод на Go 1.27 (проверено):
//
//	2 1 0     — второй цикл, defer с аргументом
//	2 1 0     — первый цикл, defer с замыканием
//	defer3
//	defer2
//	defer1
//
// Девять defer сложились в один стек и выполняются строго в обратном порядке
// объявления: сначала весь последний цикл, потом предыдущий, потом три первых.
//
// ИСТОРИЧЕСКАЯ ЛОВУШКА, которую всё ещё спрашивают на собесах.
// Замыкание захватывает саму ПЕРЕМЕННУЮ i, а не её значение. ДО Go 1.22
// переменная цикла была ОДНА на все итерации, и к моменту выполнения defer
// в ней лежало 3 — этот код печатал "3 3 3". С 1.22 на каждой итерации
// создаётся своя i, поэтому теперь "2 1 0".
//
// Поведение выбирается по версии в go.mod, а НЕ по установленному тулчейну.
// У нас go 1.27 — новая семантика. Но в любом легаси-проекте с go < 1.22
// ты увидишь старое, и там это источник настоящих багов с горутинами.
//
// `defer fmt.Println(i)` (без замыкания) печатал "2 1 0" в ЛЮБОЙ версии,
// потому что аргумент вычисляется в момент объявления defer. До 1.22 разница
// между двумя этими строчками была принципиальной, сейчас видна только
// на горутинах, которые переживают итерацию.
func DeferDemo() {
	defer fmt.Println("defer1")
	defer fmt.Println("defer2")
	defer fmt.Println("defer3")

	for i := 0; i < 3; i++ {
		defer func() { fmt.Println(i) }() // захват переменной → 3 3 3
	}

	for i := 0; i < 3; i++ {
		defer fmt.Println(i) // захват значения → 2 1 0
	}
}

// RuneVsByte — ты спросил "а как?".
//
// len(s) — байты, это дёшево: длина лежит прямо в заголовке строки, O(1).
// Руны считает utf8.RuneCountInString — она проходит строку и смотрит
// стартовые байты последовательностей, O(n).
//
// Альтернатива len([]rune(s)) даёт тот же результат, но АЛЛОЦИРУЕТ новый
// слайс на 4 байта на символ и копирует туда всё. На горячем пути так не делают.
//
// Третий способ, если нужны сами символы: for i, r := range s — range по строке
// идёт по рунам, r имеет тип rune, а i прыгает по БАЙТОВЫМ индексам (0,2,4...
// для кириллицы). Именно поэтому s[i] и range s дают разное.
func RuneVsByte(s string) (bytes, runes int) {
	return len(s), utf8.RuneCountInString(s)
}
