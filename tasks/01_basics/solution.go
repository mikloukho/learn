// СОБЕС (твои ответы + правки):
//
//   - Чем `var x int` отличается от `x := 0`? Где нельзя использовать `:=`?
//     ТЫ: "где значения еще нет". Почти. Точнее: := НЕЛЬЗЯ на уровне пакета
//     (вне функции) и нельзя, когда все переменные слева уже объявлены —
//     нужна хотя бы одна новая. var работает везде и не требует значения.
//
//   - Что такое нулевое значение и почему нет null?
//     ТЫ: "значение по умолчанию, а хз почему". Причина есть, и её спрашивают:
//     Go гарантирует, что ЛЮБАЯ память после объявления валидна и обнулена.
//     Нет состояния "не инициализировано" — нет и половины классa багов.
//     nil это не "нет значения", а нулевое значение конкретных типов:
//     указателя, слайса, мапы, канала, функции, интерфейса. У int его быть
//     не может, потому что int — это просто 8 байт, там нечему быть "пустым".
//
//   - Массив и слайс: что копируется?
//     ТЫ: верно. Добавлю точности: слайс — структура из ТРЁХ полей
//     (указатель, len, cap). Копируются они, массив под ними общий.
//
//   - Что напечатают три defer подряд?
//     ТЫ: "3 вывода". Вопрос был про ПОРЯДОК — обратный, LIFO. См. DeferDemo.
//
//   - Почему rune это не byte? len("привет")?
//     ТЫ: верно, 12. rune это псевдоним int32 (кодовая точка Unicode),
//     byte — псевдоним uint8 (один байт). Кириллица занимает 2 байта.
